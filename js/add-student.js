function _fsDuesRowYearChange(rowId) {
  const yearSel  = document.getElementById(`fs_drYear_${rowId}`);
  const monthWrap= document.getElementById(`fs_drMonthWrap_${rowId}`);
  const amtWrap  = document.getElementById(`fs_drAmtWrap_${rowId}`);
  const grid     = document.getElementById(`fs_drMonthGrid_${rowId}`);
  if (!yearSel || !grid) return;

  const year = yearSel.value;
  if (!year) {
    if (monthWrap) monthWrap.style.display = 'none';
    if (amtWrap)  amtWrap.style.display   = 'none';
    return;
  }

  const MONTHS = ['June','July','August','September','October','November','December',
                  'January','February','March','April','May'];
  grid.innerHTML = MONTHS.map(m => `
    <button type="button"
      data-month="${m}" data-paid="0"
      onclick="_fsDuesRowToggleMonth(this, ${rowId})"
      style="padding:7px 4px;border-radius:8px;border:1px solid rgba(224,82,82,0.55);
             background:rgba(224,82,82,0.15);color:var(--danger);font-size:12px;
             font-weight:600;cursor:pointer;transition:all 0.15s;text-align:center;"
      title="${m} — unpaid">
      ${m.slice(0,3)}
    </button>`).join('');

  if (monthWrap) monthWrap.style.display = '';
  if (amtWrap)  amtWrap.style.display   = 'flex';
  _fsDuesRowRecalc(rowId);
}

function _fsDuesRowToggleMonth(btn, rowId) {
  const isPaid = btn.dataset.paid === '1';
  if (isPaid) {
    btn.dataset.paid     = '0';
    btn.style.background  = 'rgba(224,82,82,0.15)';
    btn.style.borderColor = 'rgba(224,82,82,0.55)';
    btn.style.color       = 'var(--danger)';
    btn.style.cursor      = 'pointer';
    btn.style.opacity     = '1';
    btn.innerHTML = btn.dataset.month.slice(0,3);
    btn.title = btn.dataset.month + ' — unpaid';
  } else {
    btn.dataset.paid     = '1';
    btn.style.background  = 'rgba(82,200,122,0.18)';
    btn.style.borderColor = 'rgba(82,200,122,0.55)';
    btn.style.color       = 'var(--success)';
    btn.style.cursor      = 'default';
    btn.style.opacity     = '0.85';
    btn.innerHTML = btn.dataset.month.slice(0,3) + '<br><span style="font-size:8px;font-weight:700">✓PAID</span>';
    btn.title = btn.dataset.month + ' — paid';
  }
  _fsDuesRowRecalc(rowId);
}

function _fsDuesRowRecalc(rowId) {
  const grid     = document.getElementById(`fs_drMonthGrid_${rowId}`);
  const amtEl    = document.getElementById(`fs_drAmt_${rowId}`);
  const countEl  = document.getElementById(`fs_drCount_${rowId}`);
  const rateEl   = document.getElementById(`fs_drRateLabel_${rowId}`);
  const prevCls  = document.getElementById(`fs_drCls_${rowId}`)?.value || '';
  if (!grid) return;

  const allBtns    = Array.from(grid.querySelectorAll('button[data-month]'));
  const unpaidMths = allBtns.filter(b => b.dataset.paid !== '1').map(b => b.dataset.month);
  const rate = prevCls ? _flRateForClass(prevCls, 0) : 0;   // L2/L8: one resolver
  const total = unpaidMths.length * rate;

  if (amtEl)   amtEl.value    = total > 0 ? total : '';
  if (countEl) countEl.textContent = unpaidMths.length > 0
    ? `${unpaidMths.length} unpaid month${unpaidMths.length > 1 ? 's' : ''}`
    : 'All paid — no dues';
  if (rateEl) {
    if (!prevCls)   rateEl.textContent = '← Select previous class first.';
    else if (!rate) rateEl.textContent = `No fee rate for ${prevCls}.`;
    else            rateEl.textContent = `₹${fmtNum(rate)}/mo (${prevCls}) × ${unpaidMths.length} unpaid =`;
  }
  _fsUpdateGrandTotal();
  _fsSerializeDues();
}

function _fsUpdateGrandTotal() {
  const container = document.getElementById('fs_prevDuesContainer');
  const gtWrap    = document.getElementById('fs_prevDuesGrandTotalWrap');
  const gtEl      = document.getElementById('fs_prevDuesGrandTotal');
  if (!container || !gtEl) return;

  const rows = container.querySelectorAll('[id^="fs_duesRow_"]');
  let grand = 0;
  rows.forEach(row => {
    const rid = row.id.replace('fs_duesRow_', '');
    const amt = parseFloat(document.getElementById(`fs_drAmt_${rid}`)?.value || 0);
    grand += amt;
  });

  if (gtEl) gtEl.textContent = '₹' + fmtNum(grand);
  if (gtWrap) gtWrap.style.display = grand > 0 || rows.length > 1 ? 'flex' : 'none';
}

// Serialize all dues rows into fs_prevDuesJson hidden field.
// Also back-fills legacy fields (fs_outstandingYearValue, fs_outstandingMonthsJson, fs_outstanding)
// from the FIRST row so saveStudent()'s existing read still works.
function _fsSerializeDues() {
  const container = document.getElementById('fs_prevDuesContainer');
  if (!container) return;

  const rows = container.querySelectorAll('[id^="fs_duesRow_"]');
  const _fullToShort = {June:'Jun',July:'Jul',August:'Aug',September:'Sep',October:'Oct',
    November:'Nov',December:'Dec',January:'Jan',February:'Feb',March:'Mar',April:'Apr',May:'May'};

  const allDues = [];
  rows.forEach((row, idx) => {
    const rid     = row.id.replace('fs_duesRow_', '');
    const cls     = document.getElementById(`fs_drCls_${rid}`)?.value || '';
    const yr      = document.getElementById(`fs_drYear_${rid}`)?.value || '';
    const amt     = parseFloat(document.getElementById(`fs_drAmt_${rid}`)?.value || 0);
    const grid    = document.getElementById(`fs_drMonthGrid_${rid}`);
    if (!yr) return; // skip incomplete rows

    const allBtns    = grid ? Array.from(grid.querySelectorAll('button[data-month]')) : [];
    const unpaidMths = allBtns.filter(b => b.dataset.paid !== '1').map(b => b.dataset.month);
    const monthStatus = {};
    allBtns.forEach(btn => {
      const sk = _fullToShort[btn.dataset.month] || btn.dataset.month;
      monthStatus[sk] = btn.dataset.paid === '1' ? 'N/A-PAID' : 'DUE';
    });

    allDues.push({ class: cls, year: yr, amount: amt, unpaidMonths: unpaidMths, monthStatus });

    // Back-fill legacy hidden fields from row 0 (first row)
    if (idx === 0) {
      const yvEl = document.getElementById('fs_outstandingYearValue');
      const mhEl = document.getElementById('fs_outstandingMonthsJson');
      const amEl = document.getElementById('fs_outstanding');
      if (yvEl) yvEl.value = yr;
      if (mhEl) mhEl.value = JSON.stringify(unpaidMths);
      if (amEl) amEl.value = amt || '';
    }
  });

  const jsonEl = document.getElementById('fs_prevDuesJson');
  if (jsonEl) jsonEl.value = JSON.stringify(allDues);
}

