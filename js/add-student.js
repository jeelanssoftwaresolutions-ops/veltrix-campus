// Admin clicks months that ARE PAID → GREEN + locked.
// The unclicked RED months = dues stored in currentYearDueMonths.
function _fsCurYearRebuildGrid() {
  const grid      = document.getElementById('fs_curYearMonthGrid');
  const balEl     = document.getElementById('fs_curYearBalance');
  const countEl   = document.getElementById('fs_curYearMonthCount');
  const rateLabel = document.getElementById('fs_curYearRateLabel');
  const hidden    = document.getElementById('fs_curYearMonthsJson');
  if (!grid) return;

  // Reset hidden fields and totals
  if (hidden)  hidden.value  = '[]';
  if (balEl)   balEl.value   = '';
  if (countEl) countEl.textContent = '';

  const cls  = document.getElementById('fs_class')?.value || '';
  const rate = cls ? _flRateForClass(cls, 0) : 0;   // L2/L8: one resolver

  if (!cls || !rate) {
    grid.innerHTML = '<div style="font-size:12px;color:var(--muted);padding:6px 0">Select the student\'s class above to see month pills.</div>';
    if (rateLabel) rateLabel.textContent = '';
    return;
  }

  // Build month list Jun→May; only show months up to (and including) the current month
  const MONTHS = ['June','July','August','September','October','November','December',
                  'January','February','March','April','May'];
  const now        = nowIST(); /* ITEM 01 FIX: IST, not device timezone */
  const curMonth   = now.getMonth(); // 0=Jan … 11=Dec

  // Map calendar month index to academic sequence index (June=0 … May=11)
  function toAcadIdx(calIdx) {
    return calIdx >= 5 ? calIdx - 5 : calIdx + 7;
  }
  const currentAcadIdx = toAcadIdx(curMonth);

  // Only render months Jun→current month
  const available = MONTHS.slice(0, currentAcadIdx + 1);

  // ALL months start RED (unpaid/due) — admin clicks to mark GREEN (paid)
  grid.innerHTML = available.map(m => `
    <button type="button"
      data-month="${m}"
      data-paid="0"
      onclick="_fsCurYearToggleMonth(this)"
      style="padding:7px 4px;border-radius:8px;border:1px solid rgba(224,82,82,0.55);
             background:rgba(224,82,82,0.15);backdrop-filter:blur(4px);
             color:var(--danger);font-size:12px;font-weight:600;cursor:pointer;
             transition:all 0.15s ease;text-align:center;"
      title="${m} — unpaid (click to mark as paid)">
      ${m.slice(0,3)}
    </button>`).join('');

  if (rateLabel) rateLabel.textContent = cls ? `Rate: ₹${fmtNum(rate)}/month (${cls})` : '';
  _fsCurYearRecalc();
}

// REVERSED: clicking marks a month as PAID (green locked). Un-clicking → RED unpaid.
function _fsCurYearToggleMonth(btn) {
  const isPaid = btn.dataset.paid === '1';
  if (isPaid) {
    btn.dataset.paid  = '0';
    btn.style.background  = 'rgba(224,82,82,0.15)';
    btn.style.borderColor = 'rgba(224,82,82,0.55)';
    btn.style.color       = 'var(--danger)';
    btn.style.cursor      = 'pointer';
    btn.style.opacity     = '1';
    btn.innerHTML = btn.dataset.month.slice(0,3);
    btn.title = btn.dataset.month + ' — unpaid (click to mark as paid)';
  } else {
    btn.dataset.paid  = '1';
    btn.style.background  = 'rgba(82,200,122,0.18)';
    btn.style.borderColor = 'rgba(82,200,122,0.55)';
    btn.style.color       = 'var(--success)';
    btn.style.cursor      = 'default';
    btn.style.opacity     = '0.85';
    btn.innerHTML = btn.dataset.month.slice(0,3) + '<br><span style="font-size:8px;letter-spacing:0.5px;font-weight:700">✓ PAID</span>';
    btn.title = btn.dataset.month + ' — marked as paid';
  }
  _fsCurYearRecalc();
}

function _fsCurYearRecalc() {
  const grid      = document.getElementById('fs_curYearMonthGrid');
  const balEl     = document.getElementById('fs_curYearBalance');
  const countEl   = document.getElementById('fs_curYearMonthCount');
  const rateLabel = document.getElementById('fs_curYearRateLabel');
  const hidden    = document.getElementById('fs_curYearMonthsJson');
  if (!grid) return;

  // REVERSED: unpaid = months NOT marked paid (data-paid != '1')
  const allBtns      = Array.from(grid.querySelectorAll('button[data-month]'));
  const unpaidMonths = allBtns.filter(b => b.dataset.paid !== '1').map(b => b.dataset.month);
  if (hidden) hidden.value = JSON.stringify(unpaidMonths);

  const cls  = document.getElementById('fs_class')?.value || '';
  const rate = cls ? _flRateForClass(cls, 0) : 0;   // L2/L8: one resolver
  const total = unpaidMonths.length * rate;

  if (balEl)   balEl.value = total > 0 ? total : '';
  if (countEl) countEl.textContent = unpaidMonths.length > 0
    ? `${unpaidMonths.length} unpaid month${unpaidMonths.length !== 1 ? 's' : ''} × ₹${fmtNum(rate)} = ₹${fmtNum(total)} due`
    : 'All months paid — no current dues';
  if (rateLabel) rateLabel.textContent = cls && rate
    ? `Rate: ₹${fmtNum(rate)}/month (${cls})`
    : '';
}
