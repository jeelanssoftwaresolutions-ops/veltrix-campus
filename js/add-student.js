async function saveStudent(isExisting) {
  // ITEM 11 FIX (Duplicate Student Records on Double-Click Import):
  // Guard against double/rapid-repeat clicks at the submission-handler level.
  // A module-level in-flight flag blocks re-entrant calls even if the click
  // handler somehow fires twice before the DOM update below takes effect,
  // and disabling the button removes the visual affordance to click again.
  if (saveStudent._inFlight) return;
  saveStudent._inFlight = true;
  const _saveBtn = document.getElementById('saveStudentBtn');
  const _saveBtnOrigHTML = _saveBtn ? _saveBtn.innerHTML : null;
  if (_saveBtn) {
    _saveBtn.disabled = true;
    _saveBtn.style.pointerEvents = 'none';
    _saveBtn.style.opacity = '0.6';
    _saveBtn.innerHTML = `${iconPlus} ${isExisting ? 'Importing…' : 'Saving…'}`;
  }
  try {
  // COLONEL'S CHANGE #2: feeSno removed per CHG-006. dob/pen/address/previousSchool/feeWaiver also removed previously.
  // CHG-014: admissionDate re-added as a required field for the stat card & audit purposes
  const admissionDateRaw = getVal('fs_admissionDate');
  const data = {
    name:           getVal('fs_name'),
    gender:         getVal('fs_gender'),
    block:          getVal('fs_block'),
    class:          getVal('fs_class'),
    section:        getVal('fs_section'),
    // [CHG-020] rollNumber removed
    admissionNumber:getVal('fs_admNo'),
    parentName:     getVal('fs_parent'),
    contact:        getVal('fs_contact'),
    status:         'active',
    createdAt:      firebase.firestore.FieldValue.serverTimestamp(),
    createdBy:      currentUser.uid,
    type:           isExisting ? 'existing' : 'new',
    // CHG-014: store admissionDate as Timestamp; default to today if blank
    admissionDate:  admissionDateRaw
      // ITEM: date-only fact — anchored at 12:00 IST via the shared converter, not
      // UTC midnight (which stores 05:30 IST and can tip onto the wrong day).
      ? istTimestampFromDateInput(admissionDateRaw, 'noon')
      : firebase.firestore.FieldValue.serverTimestamp()
  };
  if (isExisting) {
    // BUG-M07 FIX: monthlyFee is derived from the locked fee schedule, not from DOM input.
    // This prevents staff from manually entering a wrong monthly fee for existing students.
    // L2/L8: through the ONE resolver — a class name with stray whitespace would
    // otherwise store a monthlyFee of 0 on a brand-new student, and every screen
    // would then price them from that zero.
    data.monthlyFee         = (typeof _flRateForClass === 'function')
                                ? _flRateForClass(data.class, 0)
                                : _flRateForClass(data.class, 0);   // L2/L8: one resolver

    // ── MULTI-YEAR DUES: read fs_prevDuesJson (array of all previous-year rows) ──
    const allPrevDues = JSON.parse(document.getElementById('fs_prevDuesJson')?.value || '[]');
    let totalPrevBalance = 0;

    if (allPrevDues.length > 0) {
      // Store the full multi-year array for future reference
      data.openingOutstandingDues = allPrevDues;

      // For backward-compat: populate legacy single-year fields from the OLDEST year
      // (oldest = lowest year number) so _classifyDueYear & Past Due module still work.
      const sorted = [...allPrevDues].sort((a, b) => {
        const ya = parseInt((a.year||'').split('-')[0] || '0');
        const yb = parseInt((b.year||'').split('-')[0] || '0');
        return ya - yb; // ascending — oldest first
      });
      const oldest = sorted[0];
      data.openingOutstandingYear   = oldest.year;
      data.openingOutstandingClass  = oldest.class || data.class;
      data.openingOutstandingMonths = oldest.unpaidMonths || [];
      data.academicYear             = oldest.year;
      data.prevYearMonthStatus      = oldest.monthStatus || {};

      // outstandingBalance = sum of all previous-year dues
      totalPrevBalance = allPrevDues.reduce((s, r) => s + (r.amount || 0), 0);
      data.outstandingBalance = totalPrevBalance;
    } else {
      // Fallback: try legacy single-row fields (backward compat with old saves)
      const outstandingYear    = document.getElementById('fs_outstandingYearValue')?.value || '';
      const outstandingMonths  = JSON.parse(document.getElementById('fs_outstandingMonthsJson')?.value || '[]');
      const outstandingPrevCls = document.getElementById('fs_outstandingPrevClass')?.value || '';
      data.outstandingBalance  = parseFloat(document.getElementById('fs_outstanding')?.value || 0);
      if (outstandingYear && outstandingMonths.length > 0) {
        data.openingOutstandingYear   = outstandingYear;
        data.openingOutstandingMonths = outstandingMonths;
        data.openingOutstandingClass  = outstandingPrevCls || data.class;
        data.academicYear             = outstandingYear;
      }
    }

    // BUG-④ FIX: legacy prevYearMonthStatus build from first row's grid (kept for old path)
    const prevMonthGrid = document.getElementById('fs_outstandingMonthGrid');
    const outstandingYear = document.getElementById('fs_outstandingYearValue')?.value || '';
    if (prevMonthGrid && outstandingYear && allPrevDues.length === 0) {
      const _fullToShort = {
        June:'Jun', July:'Jul', August:'Aug', September:'Sep', October:'Oct',
        November:'Nov', December:'Dec', January:'Jan', February:'Feb',
        March:'Mar', April:'Apr', May:'May'
      };
      const monthStatus = {};
      prevMonthGrid.querySelectorAll('button[data-month]').forEach(btn => {
        const shortKey = _fullToShort[btn.dataset.month] || btn.dataset.month;
        monthStatus[shortKey] = btn.dataset.paid === '1' ? 'N/A-PAID' : 'DUE';
      });
      data.prevYearMonthStatus = monthStatus;
    }

    // ── Current-year dues ────────────────────────────────────────────────────
    // Read months selected in the Current Year Dues section.
    // These are stored separately from openingOutstanding (which is prior-year).
    // academicYear is always set to the current year so _classifyDueYear() returns
    // 'current' and the Accumulated Rolling Dues stat card picks this student up.
    const curYearMonths  = JSON.parse(document.getElementById('fs_curYearMonthsJson')?.value || '[]');
    const curYearBalance = parseFloat(document.getElementById('fs_curYearBalance')?.value || 0) || 0;
    const curAcadYear    = _getCurrentAcademicYearStr();

    // JSS-REF-VELTRIX-2026-003 ITEM 08.2 FIX: fs_curYearMonthsJson only ever stored
    // the UNPAID months (currentYearDueMonths below). Months the admin clicked green
    // (already paid before entry, e.g. June/July) were never written to Firestore at
    // all — so Record Payment's paid-months lookup (~line 5899 fetchPaidMonthsForCurrentYear)
    // had nothing to read them from, and those already-paid months re-appeared as
    // outstanding when the payment grid loaded. Read the grid directly and persist
    // the paid side too.
    const curYearGrid = document.getElementById('fs_curYearMonthGrid');
    const curYearPaidAtEntry = curYearGrid
      ? Array.from(curYearGrid.querySelectorAll('button[data-month]'))
          .filter(b => b.dataset.paid === '1')
          .map(b => b.dataset.month)
      : [];

    // JSS-REF-VELTRIX-2026-003 ITEM 08.2 FIX: store paid-at-entry months whenever the
    // grid was shown, independent of whether any months are still due, so a student
    // onboarded with ALL current-year months already paid also gets this recorded.
    if (curYearPaidAtEntry.length > 0) {
      data.currentYearPaidMonths = curYearPaidAtEntry;
      data.currentYearDueYear    = curAcadYear;
    }

    if (curYearMonths.length > 0) {
      data.currentYearDueMonths  = curYearMonths;
      data.currentYearDueBalance = curYearBalance;
      data.currentYearDueYear    = curAcadYear;  // ← store year label explicitly for future matching
      // If the student ALSO has previous-year debt, academicYear was already set above
      // to the previous year. Override it to current so _classifyDueYear() picks up
      // the current-year dues correctly. Previous-year dues are tracked separately via
      // openingOutstandingYear / openingOutstandingMonths fields.
      data.academicYear          = curAcadYear;
      // outstandingBalance = prev-year balance + current-year balance combined
      // so the Due Fee page shows the full picture in one number.
      data.outstandingBalance    = (data.outstandingBalance || 0) + curYearBalance;
    } else if (!data.academicYear) {
      // No dues entered at all — still tag with current year so this student is
      // visible in current-year views once payments start.
      data.academicYear = curAcadYear;
    }
  }

  // Validation — COLONEL'S CHANGE #2: removed dob, pen from required list
  // CHG-014: admissionDate re-added as required
  // [CHG-016]: admissionNumber removed from required — auto-generated by system
  const required = ['name','gender','block','class','section','parentName','contact'];
  for (const f of required) {
    if (!data[f]) {
      showFormAlert('addStudentAlert', `Please fill in all required fields (marked with *).`, 'danger');
      document.getElementById('addStudentAlert')?.scrollIntoView({ behavior:'smooth', block:'center' });
      return;
    }
  }
  if (!admissionDateRaw) {
    showFormAlert('addStudentAlert', 'Please select a Date of Admission.', 'danger');
    document.getElementById('addStudentAlert')?.scrollIntoView({ behavior:'smooth', block:'center' });
    return;
  }

  // BUG-M13 / DOUBLE-ENTRY FIX:
  // For isExisting=true (Onboard Existing Student): if the student already exists
  // in Firestore (matched by admission number), UPDATE their fee/dues data only —
  // never create a duplicate record. Identity fields (name, gender, class, etc.)
  // are NOT overwritten; only fee-related fields are merged in.
  // For isExisting=false (New Admission): block on duplicate admission number as before.
  try {
    if (data.admissionNumber) {
      const dupAdm = await schoolCol('students').where('admissionNumber','==',data.admissionNumber).get();
      if (!dupAdm.empty) {
        if (isExisting) {
          // ── EXISTING STUDENT PATH: update fee data only, no new record ──────
          const existingDoc  = dupAdm.docs[0];
          const existingId   = existingDoc.id;
          // Build a fee-only update payload — never clobber identity fields
          const feeUpdate = { updatedBy: currentUser.uid, updatedAt: firebase.firestore.FieldValue.serverTimestamp() };
          const feeFields = [
            'monthlyFee','outstandingBalance','openingOutstandingYear',
            'openingOutstandingMonths','openingOutstandingClass','academicYear',
            'currentYearDueMonths','currentYearDueBalance','currentYearDueYear','currentYearPaidMonths','remainingBalance',
            'monthStatus','totalDue','monthsDue','monthsCleared','fee_status',
            'openingOutstandingDues','prevYearMonthStatus'
          ];
          feeFields.forEach(f => { if (data[f] !== undefined) feeUpdate[f] = data[f]; });
          await schoolCol('students').doc(existingId).update(feeUpdate);

          // ══════════════════════════════════════════════════════════════════════
          // F6 — ONBOARD EXISTING STUDENT WROTE FEE DATA AND NEVER RECONCILED.
          //
          // This path writes SIXTEEN fee fields straight onto a live student:
          // outstandingBalance, monthStatus, openingOutstandingDues, totalDue,
          // monthsDue, fee_status and the rest. All of it from the admission form's
          // own arithmetic -- a separate computation of what a student owes -- and
          // then it invalidated the caches and returned.
          //
          // Invalidating a cache makes the next read re-fetch the STORED figure. It
          // does not recompute it. So every screen faithfully redisplayed whatever
          // the form had just guessed, and outstandingBalance stayed at the form's
          // number until some unrelated payment happened to trigger a real recompute.
          //
          // The NEW ADMISSION path a few lines below has always called _flReconcile.
          // This branch was written as its sibling and never got one. Item 17 admits
          // no exceptions, and this was one of them.
          //
          // Non-fatal by construction: the write has already succeeded, and
          // _flReconcile never throws. A failure here leaves exactly the state that
          // existed before this block, and says so.
          // ══════════════════════════════════════════════════════════════════════
          if (typeof _flReconcile === 'function') {
            await _flReconcile(existingId, 'onboard_existing_student');
          }
          schoolCol('academicStructure').doc(`${data.class}-${data.section}`).set({
            className: data.class, section: data.section,
            studentIds: firebase.firestore.FieldValue.arrayUnion(existingId)
          }, { merge:true }).catch(() => {});
          invalidateStudentCache();
          invalidateFinanceCache();
          window._cachedDynamicYears = null;
          showFormAlert('addStudentAlert', '✅ Fee/dues data updated for existing student.', 'success');
          document.getElementById('addStudentAlert')?.scrollIntoView({ behavior:'smooth', block:'center' });
          setTimeout(() => pushNav('studentProfile', { id: existingId }), 1200);
          return;
        } else {
          // ── NEW ADMISSION PATH: block duplicate as before ──────────────────
          showFormAlert('addStudentAlert', `⚠ Admission Number "${data.admissionNumber}" is already registered. Each student must have a unique Admission Number.`, 'danger');
          document.getElementById('addStudentAlert')?.scrollIntoView({ behavior:'smooth', block:'center' });
          return;
        }
      }
    }
    // ADM-FIX: If admissionNumber is blank at save time, generate the next sequential
    // number using the STUDENT'S OWN admission year — not the current calendar year.
    // Source of year (priority): admissionDate field → outstandingYear → current year.
    if (!data.admissionNumber) {
      let admYear = String(nowIST().getFullYear());
      if (admissionDateRaw) {
        admYear = String(new Date(admissionDateRaw).getFullYear());
      } else if (data.academicYear) {
        admYear = String(data.academicYear).split('-')[0];
      } else if (data.openingOutstandingYear) {
        admYear = String(data.openingOutstandingYear).split('-')[0];
      }
      data.admissionNumber = await generateNextAdmNoForYear(admYear);
    }

    const ref = await schoolCol('students').add(data);

    // BUG-08 FIX: academicStructure update is NON-BLOCKING — student save
    // succeeds even if this fails (permissions issue or network hiccup)
    schoolCol('academicStructure').doc(`${data.class}-${data.section}`).set({
      className: data.class, section: data.section,
      studentIds: firebase.firestore.FieldValue.arrayUnion(ref.id)
    }, { merge:true }).catch(() => { /* academicStructure update failed silently — student was saved */ });

    // ══════════════════════════════════════════════════════════════════════════
    // JSS-REF-VELTRIX-2026-005 ITEM 17 — "new admission" is named in the rule.
    //
    // Admission seeds outstandingBalance from the form's own arithmetic (opening
    // dues, current-year due months, months paid at enrolment). That is a THIRD
    // computation of what a student owes, written straight to the authoritative
    // field and never checked against the engine that every screen reads. Any
    // disagreement — a month grid and a scalar that do not add up, a rate the form
    // resolved differently — became the student's permanent opening position.
    //
    // Reconciling immediately after creation makes the engine the author of that
    // number, exactly as it is for every student thereafter. The form's arithmetic
    // becomes the INPUT (grids and paid months), not the answer.
    // ══════════════════════════════════════════════════════════════════════════
    if (typeof _flReconcile === 'function') await _flReconcile(ref.id, 'new_admission');

    showFormAlert('addStudentAlert', '✅ Student saved successfully!', 'success');
    document.getElementById('addStudentAlert')?.scrollIntoView({ behavior:'smooth', block:'center' });
    invalidateStudentCache();  // clear student cache so new student appears in search immediately
    invalidateFinanceCache();  // BUG-H04 FIX: dashboard + academic stats stale after new student added
    window._cachedDynamicYears = null; // ✦ POINT 2: refresh dynamic year list after new student
    setTimeout(() => pushNav('studentProfile', { id:ref.id }), 1200);
  } catch(e) {
    showFormAlert('addStudentAlert', 'Error saving student: ' + e.message, 'danger');
    document.getElementById('addStudentAlert')?.scrollIntoView({ behavior:'smooth', block:'center' });
  }
  } finally {
    // ITEM 11 FIX: always release the in-flight guard and restore the button,
    // regardless of which return/throw path was taken above, so a genuine
    // retry after a validation error or network failure is still possible —
    // only true concurrent double-clicks are blocked.
    saveStudent._inFlight = false;
    if (_saveBtn) {
      _saveBtn.disabled = false;
      _saveBtn.style.pointerEvents = '';
      _saveBtn.style.opacity = '';
      if (_saveBtnOrigHTML !== null) _saveBtn.innerHTML = _saveBtnOrigHTML;
    }
  }
}

