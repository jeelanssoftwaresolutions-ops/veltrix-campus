function _fsGetYearOptions() {
  const now = nowIST(); /* ITEM 01 FIX: IST, not device timezone */
  const curStart = _getAcademicYear().yearStart;   // L3: one definition of the June boundary
  let opts = '<option value="">— select year —</option>';
  // JSS-REF-VELTRIX-2026-005 ITEM 7: opening dues are only ever carried forward for the last TWO
  // academic years, so offer exactly those. ROLLING, not hardcoded — curStart is derived from
  // today's IST date above, so the window shifts automatically each academic year with no code
  // change (in 2026-27 this yields 2025-26 + 2024-25; in 2027-28 it yields 2026-27 + 2025-26).
  const _PREV_YEARS_OFFERED = 2;
  for (let i = 1; i <= _PREV_YEARS_OFFERED; i++) {
    const s = curStart - i;
    opts += `<option value="${s}-${s+1}">${s}–${s+1}</option>`;
  }
  return opts;
}

